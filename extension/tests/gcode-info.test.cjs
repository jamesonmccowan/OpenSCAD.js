const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

const load = () => import('../webview/gcode-info.mjs');
const SAMPLE = path.join(__dirname, '../../references/scad sample files/viewer-calibration.gcode');

test('slicer-style metadata is read from original fixture header and footer comments', async () => {
  const { parseGcodeInfo } = await load();
  const source = await fs.readFile(SAMPLE, 'utf8');
  const { gcodeFixture } = await import('../../scripts/build-gcode-fixture.js');
  assert.equal(source, gcodeFixture(), 'The fixture must remain reproducible from its original generator');
  assert.equal(source.match(/^;LAYER_CHANGE$/gm).length, 55);
  assert.equal(source.match(/^G1 X\d+ Y\d+ E/gm).length, 221);
  assert.doesNotMatch(source, /(?:machine|filament)_(?:start|end)_gcode|M10[49]|M1[49]0|G28/);
  assert.deepEqual(parseGcodeInfo(source), {
    slicer: 'OpenSCAD.js fixture generator',
    printer: 'Synthetic test printer',
    seconds: 123,
    filamentMm: 111,
    filamentG: 0.28,
    colours: ['#000000', '#FF00FF', '#FFFF00', '#0080FF', '#FFFFFF'],
    bed: { x: 200, y: 200 },
    printableHeight: 200,
    layerCount: 55,
  });
});

test('Cura headers and missing metadata are handled', async () => {
  const { parseGcodeInfo, formatDuration } = await load();
  const cura = parseGcodeInfo(';FLAVOR:Marlin\n;TIME:3725\n;Filament used: 1.25m\n;MACHINE_NAME:Creality Ender-3\nG1 X1 Y1 E1\n');
  assert.equal(cura.slicer, 'Cura');
  assert.equal(cura.printer, 'Creality Ender-3');
  assert.equal(cura.seconds, 3725);
  assert.equal(cura.filamentMm, 1250);
  const empty = parseGcodeInfo('G1 X1 Y1 E1\n');
  assert.equal(empty.seconds, undefined);
  assert.equal(empty.filamentMm, undefined);
  assert.equal(empty.bed, undefined);
  assert.deepEqual(empty.colours, []);
  assert.equal(formatDuration(3725), '1h 2m');
  assert.equal(formatDuration(1281), '21m 21s');
  assert.equal(formatDuration(90061), '1d 1h 1m');
});

test('PrusaSlicer, OrcaSlicer and Bambu Studio generator banners remain recognized', async () => {
  const { parseGcodeInfo } = await load();
  for (const generator of ['PrusaSlicer 2.9.0', 'OrcaSlicer 2.3.1', 'BambuStudio 2.0.0']) {
    const source = `; generated by ${generator} on 2026-01-01 at 00:00:00\n; total layer number = 2\n; filament used [mm] = 1,2\n; total filament used [g] = 0.03\n`;
    const info = parseGcodeInfo(source);
    assert.equal(info.slicer, generator);
    assert.equal(info.layerCount, 2);
    assert.equal(info.filamentMm, 3);
    assert.equal(info.filamentG, 0.03);
  }
});

test('toolpath analysis tracks layer heights and excludes purge lines from bounds', async () => {
  const { analyzeToolpath } = await load();
  const move = (params, comment) => ({ gcode: 'g1', params, comment });
  const layers = [
    { commands: [move({ x: 0, y: 0, z: 0.2 })] },
    { commands: [{ gcode: '', params: {}, comment: 'TYPE:Custom' }, move({ x: 100, y: 0, e: 5 }), { gcode: '', params: {}, comment: 'TYPE:Outer wall' }, move({ x: 50, y: 50 }), move({ x: 60, y: 50, e: 1 })] },
    { commands: [move({ z: 0.4 }), move({ x: 60, y: 60, e: 1 })] },
  ];
  const { bounds, layerZ } = analyzeToolpath(layers);
  assert.deepEqual(bounds, { min: [50, 50, 0.2], max: [60, 60, 0.4] });
  assert.deepEqual(layerZ, [null, 0.2, 0.4]);
});
